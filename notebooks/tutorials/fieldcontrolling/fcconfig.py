def make_vae_config(resolution=VAE_PATCH):
    """2D VAE with compression factor F = 8 (three downsamplings) and C_l = 4.

    `ch_mult` has four entries, and the VAE downsamples at every level but the
    last, so F = 2^(len(ch_mult) - 1) = 8 -- the same factor as the 3D production
    autoencoder.
    """
    return diffsci2.nets.VAENetConfig(
        dimension=2,
        in_channels=1,
        out_channels=1,
        z_channels=Z_DIM,
        z_dim=Z_DIM,
        ch=32,
        ch_mult=[1, 2, 4, 4],     # -> F = 8
        num_res_blocks=2,
        attn_resolutions=[],
        dropout=0.0,
        resolution=resolution,
        has_mid_attn=False,       # no attention anywhere: keeps the RF finite
        resamp_with_conv=True,
        attn_type="vanilla",
        tanh_out=False,
        input_bias=True,
        output_bias=True,
        with_time_emb=False,
        double_z=True,
        num_groups=32,
        patch_size=None,
        memory_efficient_variant=False,
        use_flash_attention=True,
        minimal_rf_mode=False,
    )


def make_vae(resolution=VAE_PATCH):
    """Fresh (untrained) VAEModule."""
    net = diffsci2.nets.VAENet(config=make_vae_config(resolution))
    return diffsci2.models.VAEModule(
        config=diffsci2.models.VAEModuleConfig(), encdec=net
    )


def make_punet_config(cond_dropout=0.1):
    """2D PUNetG mirroring the 3D production configuration used in the thesis.

    Fully convolutional, no self-attention -- which is exactly what makes the
    model shift-invariant and free of spurious long-range correlations, the
    architectural assumption the field-controlling argument rests on.
    """
    return diffsci2.nets.PUNetGConfig(
        input_channels=Z_DIM,
        output_channels=Z_DIM,
        dimension=2,
        model_channels=MODEL_CHANNELS,
        channel_expansion=[2, 4],
        number_resnet_downward_block=2,
        number_resnet_upward_block=2,
        number_resnet_attn_block=0,        # 0 -> no attention at all
        number_resnet_before_attn_block=3,
        number_resnet_after_attn_block=3,
        kernel_size=3,
        in_out_kernel_size=3,
        in_embedding=False,
        time_projection_scale=10.0,
        input_projection_scale=1.0,
        transition_scale_factor=2,
        transition_kernel_size=3,
        dropout=0.1,
        cond_dropout=cond_dropout,
        first_resblock_norm="GroupLN",
        second_resblock_norm="GroupRMS",
        affine_norm=True,
        convolution_type="default",
        num_groups=1,
        attn_residual=False,
        attn_type="default",
        bias=True,
    )


def make_flow_model(conditional=True, cond_dropout=0.1):
    """PUNetG denoiser. `conditional=False` builds the same network without the
    conditioning embedder -- which is how the *implicit unconditional* model of
    the thesis is obtained from the very same weights (generation case 7)."""
    if conditional:
        embedder = diffsci2.nets.ScalarEmbedder(dembed=MODEL_CHANNELS, key="porosity")
    else:
        embedder = None
    return diffsci2.nets.PUNetG(
        make_punet_config(cond_dropout), conditional_embedding=embedder
    )


def make_si_module(model, autoencoder=None):
    """EDM-parameterised score-interpolant module, same settings as the pipeline."""
    config = diffsci2.models.SIModuleConfig.from_edm_sigma_space(
        sigma_min=SIGMA_MIN,
        sigma_max=SIGMA_MAX,
        sigma_data=SIGMA_DATA,
        initial_norm=INITIAL_NORM,
        loss_formulation="denoiser",
    )
    return diffsci2.models.SIModule(
        config=config, model=model, autoencoder=autoencoder
    )


