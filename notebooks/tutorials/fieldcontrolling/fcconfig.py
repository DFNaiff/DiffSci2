def porosity_of(binary):
    """Pore fraction of a binary array under the solid = 1 convention."""
    return float(1.0 - np.asarray(binary).mean())


# --- the porosity field, one canonical definition -----------------------------
# Notebook 01 defines these inline, because computing the field is what it teaches.
# The copies here are what notebooks 03-05 import, so that the *realised* field of a
# generated image is computed exactly the way the conditioning field was, and the two
# are comparable. Both mirror scripts/old/0007-porosity-field-evaluation.py:
#     calculate_porosity_field_full(volume, kernel_size) -> average_volume(field, F)

def porosity_field_valid(binary, window=None):
    """Local pore fraction, 'valid' convolution. Shape shrinks by (window - 1)."""
    import scipy.signal
    window = WINDOW if window is None else window
    kernel = np.ones((window, window), dtype=np.float32) / window ** 2
    pore = 1.0 - np.asarray(binary, dtype=np.float32)
    return scipy.signal.fftconvolve(pore, kernel, mode='valid')


def porosity_field_full(binary, window=None):
    """Local pore fraction, 'same' convolution with boundary-count normalisation.

    Values within `window // 2` of the border are averaged over fewer than
    window**2 real voxels; crop inward by that radius before trusting them.
    """
    import scipy.signal
    window = WINDOW if window is None else window
    pore = 1.0 - np.asarray(binary, dtype=np.float32)
    numerator = scipy.signal.fftconvolve(
        pore, np.ones((window, window), dtype=np.float32), mode='same')
    count_h = scipy.signal.fftconvolve(np.ones(pore.shape[0]), np.ones(window), mode='same')
    count_w = scipy.signal.fftconvolve(np.ones(pore.shape[1]), np.ones(window), mode='same')
    return numerator / (count_h[:, None] * count_w[None, :])


def to_latent(field, factor=None):
    """Average-pool a pixel-resolution field down to the latent grid."""
    import torch.nn.functional as F_
    factor = F if factor is None else factor
    t = torch.from_numpy(np.ascontiguousarray(field, dtype=np.float32))[None, None]
    return F_.avg_pool2d(t, kernel_size=factor, stride=factor)[0, 0].numpy()


def realised_field(binary, window=None, factor=None):
    """The porosity field a generated (or real) binary image actually has.

    IMPORTANT: this is a window-`window` local average, *then* pooled by `factor`.
    Pooling the binary image straight down by `factor` is a different quantity --
    the pore fraction of each factor x factor block, i.e. a window-8 field -- and
    is not comparable to the window-129 conditioning field.
    """
    return to_latent(porosity_field_full(binary, window), factor)


def field_interior(field_latent, window=None, factor=None):
    """Drop the belt where the 'same'-mode field saw fewer than window**2 voxels."""
    window = WINDOW if window is None else window
    factor = F if factor is None else factor
    m = ((window - 1) // 2) // factor
    return field_latent[m:-m, m:-m] if m > 0 else field_latent


def gaussian_hellinger(p, q):
    """Closed-form Hellinger distance between Gaussian fits of two sample sets.

    This is Eq. (Hellinger) of Part II, used there to score sub-block diversity.
    """
    mp, sp = float(np.mean(p)), float(np.std(p))
    mq, sq = float(np.mean(q)), float(np.std(q))
    var = sp ** 2 + sq ** 2
    if var <= 0:
        return 0.0
    h2 = 1.0 - np.sqrt(2.0 * sp * sq / var) * np.exp(-((mp - mq) ** 2) / (4.0 * var))
    return float(np.sqrt(max(h2, 0.0)))


