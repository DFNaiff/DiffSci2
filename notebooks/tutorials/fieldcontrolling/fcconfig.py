def _strip_prefix(state_dict, prefix):
    return {k[len(prefix):]: v for k, v in state_dict.items() if k.startswith(prefix)}


def load_vae(ckpt_path=None, device=None):
    """Rebuild the tutorial VAE and load trained weights (notebook 00)."""
    if ckpt_path is None:
        ckpt_path = os.path.join(VAE_CKPT_DIR, "last.ckpt")
    module = make_vae()
    state = torch.load(ckpt_path, map_location="cpu", weights_only=False)["state_dict"]
    module.load_state_dict(state)
    module.eval()
    if device is not None:
        module.to(device)
    return module


def load_flow_weights(ckpt_path):
    """Pull the bare denoiser weights out of a Lightning SIModule checkpoint."""
    state = torch.load(ckpt_path, map_location="cpu", weights_only=False)["state_dict"]
    return _strip_prefix(state, "model.")


def load_flow_model(ckpt_path, conditional=True, device=None):
    """Rebuild the denoiser and load trained weights.

    Passing `conditional=False` loads the *same* weights into a network with no
    conditioning embedder, giving the implicit unconditional model.
    """
    model = make_flow_model(conditional=conditional)
    weights = load_flow_weights(ckpt_path)
    if not conditional:
        weights = {k: v for k, v in weights.items()
                   if not k.startswith("conditional_embedding.")}
    missing, unexpected = model.load_state_dict(weights, strict=False)
    if conditional and (missing or unexpected):
        raise RuntimeError(f"checkpoint mismatch: missing={missing} unexpected={unexpected}")
    model.eval()
    if device is not None:
        model.to(device)
    return model


